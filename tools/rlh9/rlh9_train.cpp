// rlh9_train - build rlh9_tables.h (LLRICE_ENGINE 9) from 8-bit RGB images.
// Build (from the repo root): g++ -O3 -march=native -std=c++17 -I. tools/rlh9/rlh9_train.cpp -o rlh9_train
// Usage: rlh9_train <out.h> <file|dir>... ; .ppm (P6, 8 bit) directly; .pln via the PALIC-2 decoder in env DEC
//        (DEC=palic-2 -> "palic-2 d in.pln tmp.ppm"). Optional env SKIP=<file with names to exclude, one per line>.
// One histogram pass, +0.5 smoothing, length-limited (15) Huffman lengths, nibble-packed.
#define RLH9_NO_TABLES
#define RLH9_NSYM 837
#define RLH9_TOTC 96
#include "rlh9.hpp"
#include <cstdio>
#include <cstdlib>
#include <string>
#include <set>
#include <fstream>
#include <filesystem>
#include <unistd.h>
static bool load_ppm(const char* fn, std::vector<uint8_t>& rgb, int& W, int& H) {
    FILE* f = fopen(fn, "rb"); if (!f) return false;
    char m[3] = {0}; int mx; if (fscanf(f, "%2s %d %d %d", m, &W, &H, &mx) != 4 || std::string(m) != "P6" || mx != 255) { fclose(f); return false; }
    fgetc(f); rgb.resize(size_t(W) * H * 3); bool ok = fread(rgb.data(), 1, rgb.size(), f) == rgb.size(); fclose(f); return ok;
}
static bool load_any(const std::string& fn, std::vector<uint8_t>& rgb, int& W, int& H) {
    if (fn.size() > 4 && fn.compare(fn.size() - 4, 4, ".pln") == 0) {
        const char* dec = getenv("DEC"); if (!dec) { fprintf(stderr, "set DEC for .pln\n"); return false; }
        char tpl[] = "/tmp/rlh9t_XXXXXX"; int fd = mkstemp(tpl); close(fd);
        std::string cmd = std::string("\"") + dec + "\" d \"" + fn + "\" \"" + tpl + "\" >/dev/null 2>&1";
        bool ok = std::system(cmd.c_str()) == 0 && load_ppm(tpl, rgb, W, H); std::remove(tpl); return ok;
    }
    return load_ppm(fn.c_str(), rgb, W, H);
}
int main(int argc, char** argv) {
    if (argc < 3) { fprintf(stderr, "usage: rlh9_train <out.h> <file|dir>...\n"); return 1; }
    std::set<std::string> skip;
    if (const char* sf = getenv("SKIP")) { std::ifstream in(sf); std::string l; while (std::getline(in, l)) if (!l.empty()) skip.insert(std::filesystem::path(l).stem().string()); }
    std::vector<std::string> files;
    for (int i = 2; i < argc; ++i) {
        if (std::filesystem::is_directory(argv[i])) for (auto& e : std::filesystem::directory_iterator(argv[i])) files.push_back(e.path().string());
        else files.push_back(argv[i]);
    }
    std::sort(files.begin(), files.end());
    rlh9::Counts C; int n = 0, skipped = 0; double px = 0;
    for (auto& f : files) {
        auto ext = std::filesystem::path(f).extension().string(); if (ext != ".ppm" && ext != ".pln") continue;
        if (skip.count(std::filesystem::path(f).stem().string())) { ++skipped; continue; }
        std::vector<uint8_t> rgb; int W, H; if (!load_any(f, rgb, W, H)) { fprintf(stderr, "skip (load): %s\n", f.c_str()); continue; }
        rlh9::count(C, rgb.data(), W, H); ++n; px += double(W) * H;
    }
    constexpr int PB = (rlh9::NSYM + 1) / 2;
    std::vector<uint8_t> L(rlh9::NSYM);
    FILE* o = fopen(argv[1], "w");
    fprintf(o, "// rlh9_tables.h - generated by tools/rlh9/rlh9_train.cpp: %d images, %.1f Mpx (%d excluded by SKIP).\n", n, px / 1e6, skipped);
    fprintf(o, "// Code lengths (canonical Huffman, <= 15) per table [group*48 + ctx][symbol], two symbols per byte, low nibble first.\n#pragma once\n#include <cstdint>\n");
    fprintf(o, "#define RLH9_NSYM %d\n#define RLH9_TOTC %d\nalignas(64) static const uint8_t RLH9_LEN[%d][%d] = {\n", rlh9::NSYM, rlh9::TOTC, rlh9::TOTC, PB);
    for (int tc = 0; tc < rlh9::TOTC; ++tc) {
        rlh9::huff_len(&C.c[size_t(tc) * rlh9::NSYM], rlh9::NSYM, rlh9::MAXL, L.data());
        fprintf(o, "{");
        for (int b = 0; b < PB; ++b) { const int lo = L[2 * b], hi = 2 * b + 1 < rlh9::NSYM ? L[2 * b + 1] : 0; fprintf(o, "%d%s", lo | hi << 4, b + 1 < PB ? "," : ""); }
        fprintf(o, "}%s\n", tc + 1 < rlh9::TOTC ? "," : "");
    }
    fprintf(o, "};\n"); fclose(o);
    printf("trained on %d images, %.1f Mpx, %d excluded -> %s\n", n, px / 1e6, skipped, argv[1]);
}
