// rlh9_train - build rlh9_tables.h (LLRICE_ENGINE 9) from 8-bit RGB images.
// Build (from the repo root): g++ -O3 -march=native -std=c++17 -I. tools/rlh9/rlh9_train.cpp -o rlh9_train
// Usage: rlh9_train <out.h> [-f set] [-w weight] <file|dir>... ; options apply to the inputs after them:
//        -f -1 (default): each band goes to the table set the encoder detector picks; -f 0 / -f 1: photo / screen set;
//        -w x: weight of each token (default 1). .ppm (P6, 8 bit) directly; .png via env PNG2PPM (a command "in out");
//        .pln via the PALIC-2 decoder in env DEC ("palic-2 d in.pln tmp.ppm"). Optional env SKIP=<names to exclude>.
// One histogram pass, +0.5 smoothing, length-limited (15) Huffman lengths, nibble-packed.
#define RLH9_NO_TABLES
#define RLH9_NSYM 837
#define RLH9_TOTC 192
#define RLH9_REMS 15
#include "rlh9.hpp"
#include <cstdio>
#include <cstdlib>
#include <string>
#include <set>
#include <fstream>
#include <filesystem>
#include <unistd.h>
static bool load_ppm(const char* fn, std::vector<uint8_t>& rgb, int& W, int& H) {
    FILE* f = fopen(fn, "rb"); if (!f) return false;
    char m[3] = {0}; int mx; if (fscanf(f, "%2s %d %d %d", m, &W, &H, &mx) != 4 || std::string(m) != "P6" || mx != 255) { fclose(f); return false; }
    fgetc(f); rgb.resize(size_t(W) * H * 3); bool ok = fread(rgb.data(), 1, rgb.size(), f) == rgb.size(); fclose(f); return ok;
}
static bool load_any(const std::string& fn, std::vector<uint8_t>& rgb, int& W, int& H) {
    const bool pln = fn.size() > 4 && fn.compare(fn.size() - 4, 4, ".pln") == 0, png = fn.size() > 4 && fn.compare(fn.size() - 4, 4, ".png") == 0;
    if (png) {
        const char* cv = getenv("PNG2PPM"); if (!cv) { fprintf(stderr, "set PNG2PPM for .png\n"); return false; }
        char tpl[] = "/tmp/rlh9t_XXXXXX"; int fd = mkstemp(tpl); close(fd);
        std::string cmd = std::string(cv) + " \"" + fn + "\" \"" + tpl + "\" >/dev/null 2>&1";
        bool ok = std::system(cmd.c_str()) == 0 && load_ppm(tpl, rgb, W, H); std::remove(tpl); return ok;
    }
    if (pln) {
        const char* dec = getenv("DEC"); if (!dec) { fprintf(stderr, "set DEC for .pln\n"); return false; }
        char tpl[] = "/tmp/rlh9t_XXXXXX"; int fd = mkstemp(tpl); close(fd);
        std::string cmd = std::string("\"") + dec + "\" d \"" + fn + "\" \"" + tpl + "\" >/dev/null 2>&1";
        bool ok = std::system(cmd.c_str()) == 0 && load_ppm(tpl, rgb, W, H); std::remove(tpl); return ok;
    }
    return load_ppm(fn.c_str(), rgb, W, H);
}
int main(int argc, char** argv) {
    if (argc < 3) { fprintf(stderr, "usage: rlh9_train <out.h> <file|dir>...\n"); return 1; }
    std::set<std::string> skip;
    if (const char* sf = getenv("SKIP")) { std::ifstream in(sf); std::string l; while (std::getline(in, l)) if (!l.empty()) skip.insert(std::filesystem::path(l).stem().string()); }
    struct In { std::string f; int force; double wt; };
    std::vector<In> files; int force = -1; double wt = 1.0;
    for (int i = 2; i < argc; ++i) {
        const std::string a = argv[i];
        if (a == "-f" && i + 1 < argc) { force = atoi(argv[++i]); continue; }
        if (a == "-w" && i + 1 < argc) { wt = atof(argv[++i]); continue; }
        std::vector<std::string> fs;
        if (std::filesystem::is_directory(a)) for (auto& e : std::filesystem::directory_iterator(a)) fs.push_back(e.path().string());
        else fs.push_back(a);
        std::sort(fs.begin(), fs.end()); for (auto& f : fs) files.push_back({f, force, wt});
    }
    rlh9::Counts C; int n = 0, skipped = 0; double px = 0; uint64_t nb[2] = {0, 0};
    for (auto& in : files) {
        const std::string& f = in.f;
        auto ext = std::filesystem::path(f).extension().string(); if (ext != ".ppm" && ext != ".pln" && ext != ".png") continue;
        if (skip.count(std::filesystem::path(f).stem().string())) { ++skipped; continue; }
        std::vector<uint8_t> rgb; int W, H; if (!load_any(f, rgb, W, H)) { fprintf(stderr, "skip (load): %s\n", f.c_str()); continue; }
        rlh9::count(C, rgb.data(), W, H, in.force, in.wt, nb); ++n; px += double(W) * H;
    }
    constexpr int PB = (rlh9::NSYM + 1) / 2;
    std::vector<uint8_t> L(rlh9::NSYM);
    FILE* o = fopen(argv[1], "w");
    fprintf(o, "// rlh9_tables.h - generated by tools/rlh9/rlh9_train.cpp: %d images, %.1f Mpx (%d excluded by SKIP); bands photo/screen %llu/%llu.\n",
            n, px / 1e6, skipped, (unsigned long long)nb[0], (unsigned long long)nb[1]);
    fprintf(o, "// Code lengths (canonical Huffman, <= 15) per table [set*96 + group*48 + ctx] (group 0 = Y, 1 = S)[symbol], two symbols per byte, low nibble first.\n#pragma once\n#include <cstdint>\n");
    fprintf(o, "#define RLH9_NSYM %d\n#define RLH9_TOTC %d\nalignas(64) static const uint8_t RLH9_LEN[%d][%d] = {\n", rlh9::NSYM, rlh9::TOTC, rlh9::TOTC, PB);
    for (int tc = 0; tc < rlh9::TOTC; ++tc) {
        rlh9::huff_len(&C.c[size_t(tc) * rlh9::NSYM], rlh9::NSYM, rlh9::MAXL, L.data());
        fprintf(o, "{");
        for (int b = 0; b < PB; ++b) { const int lo = L[2 * b], hi = 2 * b + 1 < rlh9::NSYM ? L[2 * b + 1] : 0; fprintf(o, "%d%s", lo | hi << 4, b + 1 < PB ? "," : ""); }
        fprintf(o, "}%s\n", tc + 1 < rlh9::TOTC ? "," : "");
    }
    fprintf(o, "};\n");
    // zU | S code lengths (<= 6) per set and S = 1..15; row S = 0 and entries z > S are 0
    constexpr int RS = rlh9::REMS + 1;
    fprintf(o, "#define RLH9_REMS %d\nstatic const uint8_t RLH9_REMLEN[%d][%d][%d] = {\n", rlh9::REMS, rlh9::NSET, RS, RS);
    for (int t = 0; t < rlh9::NSET; ++t) {
        fprintf(o, "{");
        for (int S = 0; S < RS; ++S) {
            uint8_t RL[RS] = {0};
            if (S) rlh9::huff_len(&C.rem[(size_t(t) * RS + S) * RS], S + 1, rlh9::REMB, RL);
            fprintf(o, "{"); for (int z = 0; z < RS; ++z) fprintf(o, "%d%s", RL[z], z + 1 < RS ? "," : ""); fprintf(o, "}%s", S + 1 < RS ? "," : "");
        }
        fprintf(o, "}%s\n", t + 1 < rlh9::NSET ? "," : "");
    }
    fprintf(o, "};\n"); fclose(o);
    printf("trained on %d images, %.1f Mpx, %d excluded, bands photo/screen %llu/%llu -> %s\n", n, px / 1e6, skipped, (unsigned long long)nb[0], (unsigned long long)nb[1], argv[1]);
}
